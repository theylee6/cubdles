-- Cubdles — migration 8: messaging between matches.
-- Messages are only ever written through send_message(); members read them through RLS (and Realtime,
-- which applies the same policies). Ending a match (unmatch or block) closes the conversation for both.

-- -----------------------------------------------------------------------------
-- Tables
-- -----------------------------------------------------------------------------
alter table public.matches add column last_message_at timestamptz;

create table public.messages (
  id         uuid primary key default gen_random_uuid(),
  match_id   uuid not null references public.matches (id) on delete cascade,
  sender_id  uuid not null references public.profiles (id) on delete cascade,
  body       text not null check (char_length(body) between 1 and 2000),
  client_id  uuid not null,
  created_at timestamptz not null default now(),
  unique (sender_id, client_id)
);
comment on column public.messages.client_id is 'Generated by the sender''s device; makes retries idempotent.';
create index messages_match_created_idx on public.messages (match_id, created_at desc, id desc);
create index messages_sender_created_idx on public.messages (sender_id, created_at desc);

-- How far each member has read in each conversation.
create table public.match_reads (
  match_id     uuid not null references public.matches (id) on delete cascade,
  profile_id   uuid not null references public.profiles (id) on delete cascade,
  last_read_at timestamptz not null default now(),
  primary key (match_id, profile_id)
);
create index match_reads_profile_idx on public.match_reads (profile_id);

-- -----------------------------------------------------------------------------
-- Helpers
-- -----------------------------------------------------------------------------
-- True when the signed-in member is in this match and it hasn't ended.
create or replace function private.in_active_match(p_match_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.matches m
    where m.id = p_match_id and m.ended_at is null and (select auth.uid()) in (m.user_a, m.user_b)
  )
$$;

-- Whether this member shares read receipts.
create or replace function private.shares_read_receipts(p_uid uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((select ps.send_read_receipts from public.privacy_settings ps where ps.profile_id = p_uid), true)
$$;

-- -----------------------------------------------------------------------------
-- Writing
-- -----------------------------------------------------------------------------
create or replace function public.send_message(p_match_id uuid, p_body text, p_client_id uuid)
returns public.messages language plpgsql volatile security definer set search_path = '' as $$
declare
  me uuid := auth.uid();
  m public.matches;
  other uuid;
  clean text;
  existing public.messages;
  result public.messages;
begin
  if me is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;
  if p_client_id is null then
    raise exception 'invalid_message' using errcode = 'check_violation';
  end if;

  -- A retry of a message that already went through returns the original.
  select * into existing from public.messages where sender_id = me and client_id = p_client_id;
  if existing.id is not null then
    return existing;
  end if;

  select * into m from public.matches where id = p_match_id and me in (user_a, user_b);
  if m.id is null or m.ended_at is not null then
    raise exception 'conversation_closed' using errcode = 'check_violation';
  end if;
  other := case when m.user_a = me then m.user_b else m.user_a end;

  if private.is_blocked_between(me, other) then
    raise exception 'conversation_closed' using errcode = 'check_violation';
  end if;
  if not exists (select 1 from public.profiles where id = me and status in ('active', 'paused')) then
    raise exception 'not_allowed' using errcode = '42501';
  end if;
  if not exists (select 1 from public.profiles where id = other and status in ('active', 'paused')) then
    raise exception 'recipient_unavailable' using errcode = 'check_violation';
  end if;

  -- Strip control characters (keep newlines and tabs), collapse runs of blank lines, trim.
  clean := btrim(regexp_replace(regexp_replace(coalesce(p_body, ''), '[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]', '', 'g'), '\n{3,}', E'\n\n', 'g'), E' \t\n\r');
  if char_length(clean) = 0 then
    raise exception 'empty_message' using errcode = 'check_violation';
  end if;
  if char_length(clean) > 2000 then
    raise exception 'message_too_long' using errcode = 'check_violation';
  end if;

  -- Flood protection: 20 messages a minute, 500 a day.
  if (select count(*) from public.messages where sender_id = me and created_at > now() - interval '1 minute') >= 20
     or (select count(*) from public.messages where sender_id = me and created_at > now() - interval '1 day') >= 500 then
    raise exception 'rate_limited' using errcode = 'check_violation';
  end if;

  insert into public.messages (match_id, sender_id, body, client_id)
  values (m.id, me, clean, p_client_id)
  returning * into result;

  update public.matches set last_message_at = result.created_at where id = m.id;

  -- Sending a message means you've read everything before it.
  insert into public.match_reads (match_id, profile_id, last_read_at)
  values (m.id, me, result.created_at)
  on conflict (match_id, profile_id) do update set last_read_at = greatest(public.match_reads.last_read_at, excluded.last_read_at);

  return result;
end $$;

create or replace function public.mark_conversation_read(p_match_id uuid)
returns void language plpgsql volatile security definer set search_path = '' as $$
begin
  if not private.in_active_match(p_match_id) then
    return;
  end if;
  insert into public.match_reads (match_id, profile_id, last_read_at)
  values (p_match_id, auth.uid(), now())
  on conflict (match_id, profile_id) do update set last_read_at = now();
end $$;

-- -----------------------------------------------------------------------------
-- Reading
-- -----------------------------------------------------------------------------
-- The member's open conversations, newest activity first.
create or replace function public.my_conversations()
returns table (
  match_id uuid,
  other_id uuid,
  matched_at timestamptz,
  last_message_at timestamptz,
  last_message_preview text,
  last_message_mine boolean,
  unread_count integer
)
language sql stable security definer set search_path = '' as $$
  with me as (select auth.uid() as id),
  mine as (
    select m.*, case when m.user_a = me.id then m.user_b else m.user_a end as other
    from public.matches m, me
    where m.ended_at is null and me.id in (m.user_a, m.user_b)
  )
  select
    c.id,
    c.other,
    c.created_at,
    c.last_message_at,
    left(lm.body, 140),
    lm.sender_id = (select id from me),
    (
      select count(*)::int from public.messages x
      where x.match_id = c.id and x.sender_id = c.other
        and x.created_at > coalesce((select r.last_read_at from public.match_reads r where r.match_id = c.id and r.profile_id = (select id from me)), '-infinity')
    )
  from mine c
  join public.profiles p on p.id = c.other and p.status in ('active', 'paused')
  left join lateral (
    select body, sender_id from public.messages x where x.match_id = c.id order by x.created_at desc, x.id desc limit 1
  ) lm on true
  where not private.is_blocked_between((select id from me), c.other)
  order by coalesce(c.last_message_at, c.created_at) desc
  limit 200
$$;

-- Number of conversations with unread messages (for the nav badge).
create or replace function public.unread_conversations_count()
returns integer language sql stable security definer set search_path = '' as $$
  select count(*)::int from public.my_conversations() c where c.unread_count > 0
$$;

-- When the other person last read this conversation, if they share read receipts and so do you.
create or replace function public.conversation_seen_at(p_match_id uuid)
returns timestamptz language sql stable security definer set search_path = '' as $$
  select r.last_read_at
  from public.matches m
  join public.match_reads r on r.match_id = m.id and r.profile_id = case when m.user_a = auth.uid() then m.user_b else m.user_a end
  where m.id = p_match_id
    and private.in_active_match(p_match_id)
    and private.shares_read_receipts(r.profile_id)
    and private.shares_read_receipts(auth.uid())
$$;

-- -----------------------------------------------------------------------------
-- Row-level security
-- -----------------------------------------------------------------------------
alter table public.messages enable row level security;
alter table public.match_reads enable row level security;
revoke all on public.messages, public.match_reads from anon, authenticated;
grant select on public.messages, public.match_reads to authenticated;

create policy messages_select on public.messages for select to authenticated
  using ((select private.in_active_match(match_id)));

-- Your own read state, and the other person's only if both of you share read receipts.
create policy match_reads_select on public.match_reads for select to authenticated
  using (
    profile_id = (select auth.uid())
    or (
      (select private.in_active_match(match_id))
      and (select private.shares_read_receipts(profile_id))
      and (select private.shares_read_receipts((select auth.uid())))
    )
  );

revoke all on function public.send_message(uuid, text, uuid) from public, anon;
revoke all on function public.mark_conversation_read(uuid) from public, anon;
revoke all on function public.my_conversations() from public, anon;
revoke all on function public.unread_conversations_count() from public, anon;
revoke all on function public.conversation_seen_at(uuid) from public, anon;
grant execute on function public.send_message(uuid, text, uuid) to authenticated;
grant execute on function public.mark_conversation_read(uuid) to authenticated;
grant execute on function public.my_conversations() to authenticated;
grant execute on function public.unread_conversations_count() to authenticated;
grant execute on function public.conversation_seen_at(uuid) to authenticated;
revoke all on function private.in_active_match(uuid), private.shares_read_receipts(uuid) from public, anon;
grant execute on function private.in_active_match(uuid), private.shares_read_receipts(uuid) to authenticated, service_role;

-- -----------------------------------------------------------------------------
-- Realtime (live delivery and read receipts). Policies above apply to subscribers.
-- -----------------------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table public.messages, public.match_reads;
  end if;
end $$;
